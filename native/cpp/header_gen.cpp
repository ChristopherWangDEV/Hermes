// header_gen.cpp —— 从 IR JSON 生成 C 头（`hermes header --c` 的 C++ 版）。
//
// 与 internal/header/gen_c.go 逐字节一致：这是**分发物**的一部分，用户程序
// include 它。任何排版差异都会让"同一份 IR 在两台机器上生成不同头文件"。
#include "hermes_parser.h"
#include "json_write.h"

#include <cstring>
#include <string>

namespace {

std::string sanitize(const std::string& s) {
  std::string out;
  out.reserve(s.size());
  for (char c : s) {
    if ((c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9') || c == '_') {
      out.push_back(c);
    } else {
      out.push_back('_');
    }
  }
  if (out.empty()) return "_";
  if (out[0] >= '0' && out[0] <= '9') return "_" + out;
  return out;
}

std::string sanitize_path(const std::string& p) {
  const size_t i = p.find_last_of("/\\");
  return (i == std::string::npos) ? p : p.substr(i + 1);
}

std::string upper(std::string s) {
  for (char& c : s) {
    if (c >= 'a' && c <= 'z') c = static_cast<char>(c - 'a' + 'A');
  }
  return s;
}

const char* str_of(const hm::JVal* o, const char* k) {
  const hm::JVal* v = (o != nullptr) ? o->find(k) : nullptr;
  return (v != nullptr && v->kind() == hm::JVal::kStr) ? v->as_str().c_str() : "";
}

bool bool_of(const hm::JVal* o, const char* k) {
  const hm::JVal* v = (o != nullptr) ? o->find(k) : nullptr;
  return v != nullptr && v->kind() == hm::JVal::kBool && v->as_bool(false);
}

}  // namespace

extern "C" int hm_header_gen_c(const char* ir_json, size_t len, char* out, size_t cap,
                               size_t* out_len) {
  if (ir_json == nullptr || out == nullptr || out_len == nullptr) return -1;
  hm::JVal doc;
  size_t pos = 0;
  if (!hm::parse_json(ir_json, len, &doc, &pos) || doc.kind() != hm::JVal::kObj) return -1;

  const hm::JVal* unitv = doc.find("unit");
  const std::string unit = sanitize(str_of(unitv, "name"));
  const std::string guard = upper("HERMES_" + unit + "_H");

  std::string b;
  b += "/* Generated by hermes header --c; **do not edit**. Source: " +
       sanitize_path(str_of(unitv, "entry_path")) + " */\n";
  b += "/* Dialect: C89 + <stdint.h> (D-024). Adding any system header is a violation. */\n\n";
  b += "#ifndef " + guard + "\n#define " + guard + "\n\n";
  b += "#include \"hermes/hermes_core.h\"\n\n";
  b += "#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n";

  std::string names;
  const hm::JVal* types = doc.find("types");
  if (types != nullptr && types->kind() == hm::JVal::kArr) {
    for (size_t i = 0; i < types->size(); ++i) {
      const hm::JVal* t = types->at(i);
      if (!bool_of(t, "exported")) continue;
      names += std::string("typedef struct hermes_") + unit + "_" + sanitize(str_of(t, "name")) +
               " hermes_" + unit + "_" + sanitize(str_of(t, "name")) + ";\n";
    }
  }
  if (!names.empty()) {
    b += "/* Opaque types: only pointers cross the boundary; fields are read via accessors.\n";
    b += " * Flattening turns 'a user added a field' into 'a client read the wrong offset', silently. */\n";
    b += names;
    b += "\n";
  }

  b += "/* Execute a workflow. input_json is the request body (UTF-8); out_json is allocated by this library,\n";
  b += " * the caller must call hermes_buf_free. out_json is unset when the status code is non-zero. */\n";
  int wf = 0;
  const hm::JVal* wfs = doc.find("workflows");
  if (wfs != nullptr && wfs->kind() == hm::JVal::kArr) {
    for (size_t i = 0; i < wfs->size(); ++i) {
      const hm::JVal* w = wfs->at(i);
      if (!bool_of(w, "exported")) continue;
      ++wf;
      b += "hermes_status hermes_" + unit + "_" + sanitize(str_of(w, "name")) +
           "(const hermes_buf* input_json, hermes_buf* out_json);\n";
    }
  }
  if (wf == 0) b += "/* This unit exports no workflow (type-only library). */\n";

  b += "\n#ifdef __cplusplus\n}\n#endif\n\n";
  b += "#endif /* " + guard + " */\n";

  const size_t need = b.size() + 1;
  if (need > cap) {
    *out_len = need;
    return -4;
  }
  std::memcpy(out, b.data(), b.size());
  out[b.size()] = 0;
  *out_len = need;
  return 0;
}


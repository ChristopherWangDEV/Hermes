// genlinkpolicy 把 internal/linkpolicy 的闭集生成成 C++ 表。
//
// 为什么必须生成：许可红线判据有两份实现（Go 的 compile 侧与 C++ 的 cc/compile）
// 是危险信号；手抄的表会漂移，而漂移的后果是 GPL 库被放进来。
package main

import (
	"fmt"
	"os"
	"strings"

	"hermes/internal/linkpolicy"
)

func cstr(s string) string {
	s = strings.ReplaceAll(s, `\`, `\\`)
	s = strings.ReplaceAll(s, `"`, `\"`)
	return `"` + s + `"`
}

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: genlinkpolicy <out .cpp>")
		os.Exit(2)
	}
	var b strings.Builder
	b.WriteString("// Generated by tools/genlinkpolicy -- do not edit (source: internal/linkpolicy).\n")
	b.WriteString("#include \"linkpolicy_table.h\"\n\n")
	b.WriteString("namespace hm {\n")
	b.WriteString("const LinkRule kForbiddenRules[] = {\n")
	for _, r := range linkpolicy.ForbiddenRuntimes {
		fmt.Fprintf(&b, "    {%s, %s, %s, %s},\n", cstr(r.Name), cstr(r.Licence), cstr(r.Reason), cstr(r.Source))
	}
	b.WriteString("};\n")
	fmt.Fprintf(&b, "const size_t kForbiddenRuleCount = %d;\n", len(linkpolicy.ForbiddenRuntimes))
	b.WriteString("}  // namespace hm\n")
	if err := os.WriteFile(os.Args[1], []byte(b.String()), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Printf("wrote %s (%d rules)\n", os.Args[1], len(linkpolicy.ForbiddenRuntimes))
}

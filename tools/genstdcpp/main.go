// genstdcpp 把内置 std 模块的源码生成成 C++ 表（build/std_table.cpp）。
//
// 为什么生成而不是手抄：这 4 份 `.h` 是**唯一事实源**（`internal/std/stdlib/`），
// 手抄一份进 C++ 就会有两种可能——要么漂移，要么有人忘了同步。生成物进 build/，
// 不入库，因此不可能与源不一致。
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: genstdcpp <stdlib dir> <out .cpp>")
		os.Exit(2)
	}
	dir, out := os.Args[1], os.Args[2]
	ents, err := os.ReadDir(dir)
	if err != nil {
		fmt.Fprintf(os.Stderr, "genstdcpp: %v\n", err)
		os.Exit(1)
	}
	type mod struct{ name, body string }
	var mods []mod
	for _, e := range ents {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".h") {
			continue
		}
		b, err := os.ReadFile(filepath.Join(dir, e.Name()))
		if err != nil {
			fmt.Fprintf(os.Stderr, "genstdcpp: %v\n", err)
			os.Exit(1)
		}
		mods = append(mods, mod{strings.TrimSuffix(e.Name(), ".h"), string(b)})
	}
	// 字典序：顺序影响产物字节（与 internal/std.Names 同一约定）。
	sort.Slice(mods, func(i, j int) bool { return mods[i].name < mods[j].name })

	var b strings.Builder
	b.WriteString("// Generated by tools/genstdcpp -- do not edit (source: internal/std/stdlib/*.h).\n")
	b.WriteString("#include <cstddef>\n#include <cstring>\n\n")
	b.WriteString("namespace {\nstruct StdMod { const char* name; const char* body; size_t len; };\n")
	b.WriteString("const StdMod kStd[] = {\n")
	for _, m := range mods {
		fmt.Fprintf(&b, "  {\"%s\", ", m.name)
		// C 字符串字面量转义：非可打印与需转义字符一律 \\xNN（长度另记，避免歧义）。
		b.WriteString("\"")
		for i := 0; i < len(m.body); i++ {
			c := m.body[i]
			switch c {
			case '\\':
				b.WriteString("\\\\")
			case '"':
				b.WriteString("\\\"")
			case '\n':
				b.WriteString("\\n")
			case '\t':
				b.WriteString("\\t")
			case '\r':
				b.WriteString("\\r")
			default:
				if c < 0x20 || c > 0x7e {
					fmt.Fprintf(&b, "\\x%02x", c)
					// \x 会贪婪吃掉后续十六进制字符：紧跟一个空串分割。
					b.WriteString("\" \"")
				} else {
					b.WriteByte(c)
				}
			}
		}
		fmt.Fprintf(&b, "\", %d},\n", len(m.body))
	}
	b.WriteString("};\nconst int kStdCount = (int)(sizeof(kStd) / sizeof(kStd[0]));\n}  // namespace\n\n")
	b.WriteString(`extern "C" int hm_std_count(void) { return kStdCount; }
extern "C" const char* hm_std_name(int i) {
  if (i < 0 || i >= kStdCount) return nullptr;
  return kStd[i].name;
}
extern "C" int hm_std_source(const char* name, char* out, size_t cap, size_t* out_len) {
  if (name == nullptr || out == nullptr || out_len == nullptr) return -1;
  for (int i = 0; i < kStdCount; ++i) {
    if (std::strcmp(kStd[i].name, name) != 0) continue;
    const size_t need = kStd[i].len + 1;
    if (need > cap) { *out_len = need; return -4; }
    std::memcpy(out, kStd[i].body, kStd[i].len);
    out[kStd[i].len] = 0;
    *out_len = need;
    return 0;
  }
  return -1;
}
`)
	if err := os.WriteFile(out, []byte(b.String()), 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "genstdcpp: %v\n", err)
		os.Exit(1)
	}
	fmt.Printf("wrote %s (%d modules)\n", out, len(mods))
}

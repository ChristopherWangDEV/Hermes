// genstdvariants 把 internal/std 的实现变体表生成成 C++ 表。
//
// 为什么生成：`link` 要用它判断"选中的变体是否真有该成员的实现"。手抄一份
// 进 C++ 会在下次新增 std 成员时漂移，而漂移的症状是"链接期放过了运行期才炸
// 的依赖"——与许可闭集那份表同一个理由。
package main

import (
	"fmt"
	"os"
	"sort"
	"strings"
)

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: genstdvariants <out .cpp>")
		os.Exit(2)
	}
	// 直接驱动 http 端点没有意义：这里只需要"有哪些成员、各自有哪些变体"，
	// 而那正是 ImplOf 的输入空间。用固定写法枚举，避免把 Impl 结构导出。
	type row struct {
		mod     string
		variant string
		name    string
		goImpl  bool
	}
	// 与 internal/std/variant.go 的 impls 表面逐条对应；改动那边必须同步这里，
	// 而 `TestStdVariantTableMatchesGo` 会盯着这一步。
	rows := []row{
		{"net", "go", "gnet", true}, {"net", "c", "net", false},
		{"model", "go", "gmodel", true}, {"model", "c", "model", false},
		{"runtime", "go", "gruntime", true}, {"runtime", "c", "runtime", false},
		{"json", "go", "gjson", true}, {"json", "c", "json", false},
	}
	sort.Slice(rows, func(i, j int) bool {
		if rows[i].mod != rows[j].mod {
			return rows[i].mod < rows[j].mod
		}
		return rows[i].variant < rows[j].variant
	})
	var b []string
	b = append(b, "// Generated by tools/genstdvariants -- do not edit (source: internal/std).")
	b = append(b, "#include \"std_variants.h\"")
	b = append(b, "")
	b = append(b, "namespace hm {")
	b = append(b, "const StdVariantRow kStdVariants[] = {")
	for _, r := range rows {
		b = append(b, fmt.Sprintf("    {\"%s\", \"%s\", \"%s\", %s},", r.mod, r.variant, r.name, map[bool]string{true: "true", false: "false"}[r.goImpl]))
	}
	b = append(b, "};")
	b = append(b, fmt.Sprintf("const size_t kStdVariantCount = %d;", len(rows)))
	b = append(b, "}  // namespace hm")
	if err := os.WriteFile(os.Args[1], []byte(strings.Join(b, "\n")+"\n"), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Printf("wrote %s (%d rows)\n", os.Args[1], len(rows))
}

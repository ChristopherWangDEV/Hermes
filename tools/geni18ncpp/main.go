// geni18ncpp 把语言包生成成 C++ 表（build/i18n_table.cpp）。
//
// 唯一事实源是 `i18n/hermes.rp`；Go 侧用 go:embed 读它，C++ 侧用这张生成的表。
// 生成物进 build/ 不入库 —— 两份手抄必然漂移。
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"sort"
	"strings"
)

type entry struct {
	Key          string            `json:"key"`
	Translations map[string]string `json:"translations"`
}

type pack struct {
	Entries []entry `json:"entries"`
}

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: geni18ncpp <pack.rp> <out .cpp>")
		os.Exit(2)
	}
	raw, err := os.ReadFile(os.Args[1])
	if err != nil {
		fmt.Fprintf(os.Stderr, "geni18ncpp: %v\n", err)
		os.Exit(1)
	}
	var p pack
	if err := json.Unmarshal(raw, &p); err != nil {
		fmt.Fprintf(os.Stderr, "geni18ncpp: %v\n", err)
		os.Exit(1)
	}
	sort.Slice(p.Entries, func(i, j int) bool { return p.Entries[i].Key < p.Entries[j].Key })

	var b strings.Builder
	b.WriteString("// Generated by tools/geni18ncpp -- do not edit (source: i18n/hermes.rp).\n")
	b.WriteString("#include <cstring>\n\nnamespace {\nstruct TrEntry { const char* key; const char* zh; };\n")
	b.WriteString("const TrEntry kTr[] = {\n")
	n := 0
	for _, e := range p.Entries {
		zh := e.Translations["zh-Hans"]
		if zh == "" {
			continue // 未翻译的条目在 C++ 侧没有意义：回落到英文原文
		}
		fmt.Fprintf(&b, "  {%s, %s},\n", cstr(e.Key), cstr(zh))
		n++
	}
	b.WriteString("};\nconst int kTrCount = (int)(sizeof(kTr) / sizeof(kTr[0]));\n}  // namespace\n\n")
	b.WriteString(`extern "C" const char* hm_tr(const char* key, const char* lang) {
  if (key == nullptr) return "";
  if (lang == nullptr || std::strcmp(lang, "zh") != 0) return key;
  for (int i = 0; i < kTrCount; ++i) {
    if (std::strcmp(kTr[i].key, key) == 0) return kTr[i].zh;
  }
  return key;  // no translation: fall back to the source string, never return empty
}
`)
	if err := os.WriteFile(os.Args[2], []byte(b.String()), 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "geni18ncpp: %v\n", err)
		os.Exit(1)
	}
	fmt.Printf("wrote %s (%d translated entries)\n", os.Args[2], n)
}

func cstr(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch c {
		case '\\':
			b.WriteString("\\\\")
		case '"':
			b.WriteString("\\\"")
		case '\n':
			b.WriteString("\\n")
		case '\t':
			b.WriteString("\\t")
		case '\r':
			b.WriteString("\\r")
		default:
			if c < 0x20 {
				fmt.Fprintf(&b, "\\x%02x\" \"", c)
			} else {
				b.WriteByte(c)
			}
		}
	}
	b.WriteByte('"')
	return b.String()
}

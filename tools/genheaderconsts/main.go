// genheaderconsts 把 internal/header 里的 C 片段常量生成成 C++ 字符串。
//
// 为什么生成而不是手抄：CErrorSlotDecl 是**逐字符**的 ABI 文本（C89、共享错误槽），
// 手抄一份进 C++ 必然漂移；漂移的后果是"shim 与 core_impl 的槽对不上"，
// 而症状是 last_error 永远是空的。生成物进 build/，源永远是 Go 那一个。
package main

import (
	"fmt"
	"os"
	"strings"

	"hermes/internal/header"
)

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: genheaderconsts <out .cpp>")
		os.Exit(2)
	}
	var b strings.Builder
	b.WriteString("// Generated by tools/genheaderconsts -- do not edit (source: internal/header).\n")
	b.WriteString("#include <cstddef>\n\n")
	b.WriteString("namespace hm {\n")
	write := func(name, body string) {
		fmt.Fprintf(&b, "extern const char %s[];\nconst char %s[] = R\"HERMES(", name, name)
		b.WriteString(body)
		b.WriteString(")HERMES\";\n\n")
	}
	write("kCErrorSlotDecl", header.CErrorSlotDecl)
	write("kCoreImpl", header.CoreImpl)
	b.WriteString("}  // namespace hm\n")
	if err := os.WriteFile(os.Args[1], []byte(b.String()), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Printf("wrote %s\n", os.Args[1])
}

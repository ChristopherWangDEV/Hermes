// unitErrorSlotFallback 让 unit AOT 产物在**不链** core_impl.c 时也能单独编译链接。
//
// cmd_compile_test.go 的 driver 原先只把 unit.c + drv.c 交给 clang，链接单元里
// 没有 core_impl.c；unit.c 里的 extern 声明于是会变成 undefined symbol。weak 定义
// 解决了这件事：单独链接时由它兜底；同一链接单元里若有 core_impl.c 的强定义，
// 链接器采用强定义（Mach-O weak_def / ELF weak 都会合并），所有翻译单元共享
// 同一个槽 —— 写进 unit.c 的错误与 hermes_last_error() 读到的就是同一份。
//
// 只在本仓支持的 clang/GCC 工具链上启用；其它编译器下 extern 声明仍然要求宿主
// 提供 core_impl.c（与 `hermes cc` 路径一致，那条路径总是链 core_impl.c）。
const unitErrorSlotFallback = `
/* Standalone AOT unit: a weak definition so the shared slot resolves even when
 * this translation unit is linked WITHOUT hermes_core_impl.c. When core_impl.c
 * is present its strong definition wins and both TUs share one slot. */
#if defined(__clang__) || defined(__GNUC__)
HERMES_THREAD_LOCAL struct hermes_error_slot __attribute__((weak)) hermes_last_error_slot = { 0, 0, 0, { 0 } };
#endif
`

// GenerateUnitFunc 把一个导出函数编成 C ABI 实现（`.hbc ≙ .a` 的落地）：
//
//	hermes_status hermes_<unit>_<fn>(const hermes_buf* in, hermes_buf* out);
//
// 输入/输出都是 JSON（in 是形参值，out 是返回值）。这是**静态库成员**，
// 链接期由 C 程序直接调用——不经 hermes_rt_run 解释。
//
// 当前只支持：单形参、非递归、C 后端子集内的函数体。其余如实报错。
func GenerateUnitFunc(doc *ir.Doc, unit string, fn *ir.Function) ([]byte, error) {
	if fn == nil {
		return nil, fmt.Errorf("backend(unit): nil function")
	}
	if len(fn.Params) != 1 {
		return nil, fmt.Errorf("backend(unit): only single-parameter functions are supported yet (%q has %d)", fn.Name, len(fn.Params))
	}
	if fn.Recursive {
		return nil, fmt.Errorf("backend(unit): recursive functions are not supported yet (%q)", fn.Name)
	}
	// 复用 cGen：把函数当成一个"没有外部调用的 workflow"来看。
	wf := &ir.Workflow{Name: fn.Name, Root: fn.Root, Nodes: fn.Nodes, Vars: fn.Vars, Returns: fn.Returns}
	g := &cGen{wf: wf, doc: doc, byID: make(map[int]*ir.Node, len(fn.Nodes)), varID: make(map[string]int, len(fn.Vars)), catchVars: make(map[int]string)}
	for i := range fn.Nodes {
		g.byID[fn.Nodes[i].ID] = &fn.Nodes[i]
	}
	for i := range fn.Vars {
		g.varID[fn.Vars[i].Name] = fn.Vars[i].ID
	}
	paramVar, ok := g.varID[fn.Params[0].N]
	if !ok {
		return nil, fmt.Errorf("backend(unit): parameter %q has no variable slot", fn.Params[0].N)
	}

	var body strings.Builder
	if err := g.emitStmt(&body, fn.Root, 1); err != nil {
		return nil, err
	}

	var out strings.Builder
	out.WriteString("/* Generated by hermes (unit AOT: .hbc as a static library); do not edit. */\n")
	out.WriteString("#include <stdio.h>\n#include <stdlib.h>\n#include <string.h>\n\n")
	out.WriteString("#include \"hermes/hermes_core.h\"\n\n")
	// 共享错误槽：core_impl.c 定义那个槽，unit.c 是第二处写方。这里 extern 声明 +
	// bounded-copy helper；再加一份 weak 定义，让本产物在不链 core_impl.c 时也能
	// 单独编译链接（见下方 unitErrorSlotFallback 的注释）。
	out.WriteString(header.CErrorSlotDecl)
	out.WriteString(unitErrorSlotFallback)
	out.WriteString("\n")
	out.WriteString(cPrelude)
	out.WriteString(cToJSON)

	fmt.Fprintf(&out, "/* unit AOT: %s.%s */\n", unit, fn.Name)
	fmt.Fprintf(&out, "hermes_status hermes_%s_%s(const hermes_buf* in, hermes_buf* out) {\n", unit, fn.Name)
	out.WriteString("  long hm_steps = 0; Val hm_result = hm_int(0);\n")
	out.WriteString("  char* hm_inb = 0; const char* hm_in = 0;\n")
	out.WriteString("  if (in && in->ptr) { size_t hm_n = in->len; hm_inb = (char*)malloc(hm_n + 1); memcpy(hm_inb, in->ptr, hm_n); hm_inb[hm_n] = 0; hm_in = hm_inb; }\n")
	// 绑定单形参：形参值就是整个输入 JSON。
	fmt.Fprintf(&out, "  Val var_%d = hm_parse_input(hm_in);\n", paramVar)
	// hm_error 是静态库里的全局槽，函数可能被反复调用：每次入口都清一次，
	// 避免上一次调用的错误对象（code/status/msg）泄漏到本次调用。
	// 同时清对外共享错误槽：成功调用后 hermes_last_error() 必须是 len == 0。
	out.WriteString("  hm_clear_error();\n")
	out.WriteString("  hermes_last_error_clear();\n")
	out.WriteString(body.String())
	out.WriteString("  goto hm_done;\n")
	out.WriteString("hm_fail:\n")
	out.WriteString("  { HermesError hm_e = hm_error_snapshot();\n")
	// unit 的 ABI 只回 hermes_status（HERMES_ERR_* 码空间），与 hm_error.code
	// 的 CatchType(1..5,8) 不同源，不能直传；不存在正向映射规范，故返回值保持
	// HERMES_ERR_INTERNAL 不变，只把 hm_e.code/status/msg 原样 bounded-copy 进
	// 共享错误槽（不对外暴露 code/status，宿主只读 hermes_str{ptr,len}）。
	// 快照现在被真正消费（code/status/msg 都写进槽），不再是死变量。
	out.WriteString("    size_t hm_e_len;\n")
	out.WriteString("    hm_e_len = hermes_last_error_bounded_len(hm_e.msg);\n")
	out.WriteString("    if (hm_e_len == 0) {\n")
	out.WriteString("      hermes_last_error_publish((int32_t)hm_e.code, (int32_t)hm_e.status,\n")
	out.WriteString("        \"AOT unit failed without error text\",\n")
	out.WriteString("        sizeof(\"AOT unit failed without error text\") - 1);\n")
	out.WriteString("    } else {\n")
	out.WriteString("      hermes_last_error_publish((int32_t)hm_e.code, (int32_t)hm_e.status, hm_e.msg, hm_e_len);\n")
	out.WriteString("    }\n")
	out.WriteString("    if (hm_inb) free(hm_inb);\n")
	out.WriteString("    return HERMES_ERR_INTERNAL; }\n")
	out.WriteString("hm_done:\n")
	out.WriteString("  (void)hm_steps;\n")
	out.WriteString("  if (out) { out->ptr = hm_to_json(hm_result); out->len = strlen(out->ptr); }\n")
	out.WriteString("  if (hm_inb) free(hm_inb);\n")
	out.WriteString("  return HERMES_OK;\n")
	out.WriteString("}\n")
	return []byte(out.String()), nil
}

// cToJSON 是 unit AOT 需要的 Val→JSON 序列化（与 net 运行期里的同名 helper 一致）。
// **必须与 cNetPrelude 的 hm_to_json 同源**：net 运行期与 unit AOT 输出口径分叉
// 是纯静默损坏（两份逐字重复的实现，改一处漏一处就是两种 JSON）。k=4 的 double
// 分支在两边同时加：先用 cPrelude 里的 hm_double_finite 在序列化边界拦下非有限值，
// 再用 hm_double_text 做最短往返。
const cToJSON = `
static char* hm_to_json(Val v){
  if(v.k==0){ char* b=(char*)malloc(32); snprintf(b,32,"%ld",v.i); return b; }
  if(v.k==1){ return hm_dup(v.b?"true":"false"); }
  if(v.k==3){ return hm_dup(v.s?v.s:"null"); }
  if(v.k==4){ char buf[64]; if(!hm_double_finite(v.d)){ hm_set_error(1,"non-finite double at JSON boundary"); return hm_dup("null"); } hm_double_text(v.d,buf,sizeof buf); return hm_dup(buf); }
  { const char* s=v.s?v.s:""; size_t n=strlen(s); char* b=(char*)malloc(n*6+3); size_t j=0;
    b[j++]='"';
    for(;*s;s++){ unsigned char c=(unsigned char)*s;
      if(c=='"'){ b[j++]='\\'; b[j++]='"'; }
      else if(c=='\\'){ b[j++]='\\'; b[j++]='\\'; }
      else if(c=='\n'){ b[j++]='\\'; b[j++]='n'; }
      else if(c=='\r'){ b[j++]='\\'; b[j++]='r'; }
      else if(c=='\t'){ b[j++]='\\'; b[j++]='t'; }
      else if(c<0x20){ j+=(size_t)snprintf(b+j,n*6+3-j,"\\u%04x",c); }
      else b[j++]=c; }
    b[j++]='"'; b[j]=0; return b; }
}
`

// cBackend 把 IR 降为一份**自包含 C 程序**：不含 IR JSON、不链 Go 运行时。
//
// S0 子集（docs/NATIVE-BACKEND.md §6）：seq / decl / assign / return / var /
// lit / binop / unop / interp / if / cast(恒等)。超出子集的节点一律**明确报错**，
// 不静默降级 —— 静默降级会让"编译成功但语义错了"变成最难查的一类 bug。
type cBackend struct{}

func (cBackend) Name() string { return "c" }

func (cBackend) Generate(doc *ir.Doc) ([]byte, error) {
	wf, err := pickEntryWorkflow(doc)
	if err != nil {
		return nil, err
	}
	g := &cGen{
		wf:        wf,
		doc:       doc,
		byID:      make(map[int]*ir.Node, len(wf.Nodes)),
		varID:     make(map[string]int, len(wf.Vars)),
		catchVars: make(map[int]string),
	}
	for i := range wf.Nodes {
		g.byID[wf.Nodes[i].ID] = &wf.Nodes[i]
	}
	for i := range wf.Vars {
		g.varID[wf.Vars[i].Name] = wf.Vars[i].ID
	}

	var body strings.Builder
	body.WriteString("  hm_steps = 0;\n  Val hm_result = hm_int(0);\n")
	for _, st := range g.signalStates() {
		fmt.Fprintf(&body, "  hm_pal_cond_init(&%s.cv);\n", st)
	}
	// 方案 A：只有监听 `export signal` 的槽进全局表；普通局部信号的槽
	// 留在单元内走编译期配对（零开销）。
	g.emitRegistrations(&body)
	// 入口变量 `input`：它不是 decl 绑定的，由调用方在入口赋值。
	for i := range wf.Vars {
		if wf.Vars[i].Name == "input" {
			fmt.Fprintf(&body, "  Val var_%d = hm_parse_input(argc > 1 ? argv[1] : 0);\n", wf.Vars[i].ID)
		}
	}
	if err := g.emitStmt(&body, wf.Root, 1); err != nil {
		return nil, err
	}
	// 正常落空（无 return）也走收尾；未捕获的错误跳到 hm_fail。
	body.WriteString("  goto hm_done;\n")
	// 失败出口用上标准错误对象：按值快照，退出码取 code（为 0 兜底 1），
	// stderr 带出 msg（为空时兜底 "runtime error"）。快照调用同时保证每个产物
	// 都引用 hm_error_snapshot，避免 -Wall 下新增 helper 的 unused-function 告警。
	body.WriteString("hm_fail:\n")
	body.WriteString("  { HermesError hm_e = hm_error_snapshot();\n")
	body.WriteString("    fprintf(stderr, \"hermes: %s\\n\", hm_e.msg[0] ? hm_e.msg : \"runtime error\");\n")
	body.WriteString("    return hm_e.code ? (int)hm_e.code : 1; }\n")
	// 收尾：stdout 与 `hermes run` 逐字一致（JSON 键按字母序：steps/value/workflow）。
	body.WriteString("hm_done:\n")
	// JSON 序列化边界：非有限 double 必须在**任何 printf 之前**拦下，否则
	// hm_print_json 会把 "inf"/"nan" 写进 stdout 而进程仍返回 0（非法 JSON）。
	// hm_fail 在 main 中位于 hm_done 之前，向后 goto 合法；它打印 msg 并返回非零码。
	body.WriteString("  if(hm_result.k==4 && !hm_double_finite(hm_result.d)){ hm_set_error(1,\"non-finite double at JSON boundary\"); goto hm_fail; }\n")
	body.WriteString("  printf(\"{\\\"steps\\\":%ld,\\\"value\\\":\", hm_steps);\n")
	body.WriteString("  hm_print_json(hm_result);\n")
	fmt.Fprintf(&body, "  printf(\",\\\"workflow\\\":\\\"%s\\\"}\\n\");\n", cEscape(wf.Name))
	body.WriteString("  return 0;\n")

	var out strings.Builder
	out.WriteString("/* Generated by hermes compile --backend=c; **do not edit**. */\n")
	out.WriteString("/* Self-contained: values + control flow lowered to C; no IR, no Go runtime. */\n\n")
	out.WriteString(cPrelude)
	// call_native 的 extern 原型：**编译期**按 IR 的 ret/arg_types 写死，
	// 符号由链接期 clang/ld 解析。不放进 UsesNet —— 原生符号只需要 libc +
	// 用户通过 --link-static 给的 .a，不需要 glibhermesnet.a。
	protos, err := nativePrototypes(doc)
	if err != nil {
		return nil, err
	}
	if protos != "" {
		out.WriteString("\n/* Native C ABI prototypes: emitted at compile time, resolved by the linker. */\n")
		out.WriteString("/* Duplicate symbols with different signatures keep the first declaration; */\n")
		out.WriteString("/* signature-conflict diagnostics are tracked separately. */\n")
		out.WriteString(protos)
	}
	// 只有用到 call_tool/call_model 的产物才带上 net 运行期（它 #include
	// "hermes_net.h" 并引用 hermes_net_*，要求链接 glibhermesnet.a）。
	if UsesNet(doc) {
		out.WriteString(cNetPrelude)
	}
	// ---- 槽函数段（闭包转换第 1、2 步）------------------------------------
	// 每个带捕获的 `on` 生成：一个上下文结构体 + 一个静态槽函数。
	// 槽函数签名统一是 `static int hm_slot_N(void* raw)`：
	//   · void* 是为了让所有槽能放进同一张静态表（下一步就是它）；
	//   · 返回 int 承载"已处理（1）/ 继续冒泡（0）"的短路语义。
	slots, err := g.genSlots(doc)
	if err != nil {
		return nil, err
	}
	// hm_steps 提到文件作用域：槽函数体里的一步也要计数，而它不在 main 的
	// 栈帧里。保持 static，不导出、不污染 ABI。
	out.WriteString("\nstatic long hm_steps = 0;\n")
	// 每个 (signal, channel) 一份等待状态：条件变量 + 边沿标志。
	// 静态分配，无堆、无全局锁；状态与信号/频道严格一一对应。
	for _, st := range g.signalStates() {
		fmt.Fprintf(&out, "static struct { hm_pal_cond_t cv; int flag; } %s;\n", st)
	}
	if slots != "" {
		out.WriteString("\n/* Signal slots: closure-converted. No heap, no dictionary. */\n")
		out.WriteString(slots)
	}
	out.WriteString("\nint main(int argc, char** argv) {\n  (void)argc; (void)argv;\n")
	// 每个产物入口都清一次错误对象：既是运行期正确初始化，也保证 hm_clear_error
	// 恒定被引用（-Wall 下不产生 unused-function 告警）。
	out.WriteString("  hm_clear_error();\n")
	out.WriteString(body.String())
	out.WriteString("}\n")
	return []byte(out.String()), nil
}

// signalStates 收集本单元用到的 (signal, channel) 组合。
// 键是 FNV(signal) ^ FNV(chan)：频道为全局时为 0。
// 每个组合一个静态 hm_pal_cond_t + 一个 int 标志，**没有全局锁**。
func (g *cGen) signalStates() []string {
	seen := map[uint64]bool{}
	var keys []uint64
	add := func(sig string, ch *uint64) {
		k := hashName(sig)
		if ch != nil {
			k ^= *ch
		}
		if !seen[k] {
			seen[k] = true
			keys = append(keys, k)
		}
	}
	for ni := range g.wf.Nodes {
		n := &g.wf.Nodes[ni]
		switch n.K {
		case "emit", "until":
			if n.Signal != nil {
				add(*n.Signal, n.Chan)
			}
		}
	}
	out := make([]string, 0, len(keys))
	for _, k := range keys {
		out = append(out, fmt.Sprintf("hm_sig_%d", k))
	}
	return out
}

// chanKey：频道路由返回频道哈希，全局路由返回 0。与 slot 注册用同一个键，
// 否则全局派发永远匹配不上。
func chanKey(n *ir.Node) uint64 {
	if n.Route != nil && *n.Route == 1 && n.Chan != nil {
		return *n.Chan
	}
	return 0
}

func (g *cGen) emitRegistrations(b *strings.Builder) {
	for ni := range g.wf.Nodes {
		n := &g.wf.Nodes[ni]
		if n.K != "on" || n.Exported == nil || !*n.Exported || n.Signal == nil {
			continue
		}
		fmt.Fprintf(b, "  hm_slot_register(0x%016xULL, 0x%016xULL, hm_slot_%d, (void*)0, &hm_greg_%d);\n",
			hashName(*n.Signal), chanKey(n), n.ID, n.ID)
	}
}

func sigStateName(n *ir.Node) string {
	k := hashName(*n.Signal)
	if n.Chan != nil {
		k ^= *n.Chan
	}
	return fmt.Sprintf("hm_sig_%d", k)
}

// emitUntil 生成边沿触发的等待。
//
// 语义：等"接下来的任意一次 emit"——进入等待前清标志（在同一把锁内），
// 所以历史上的 emit 不会让这次 until 立刻返回。
func (g *cGen) emitUntil(b *strings.Builder, n *ir.Node, depth int) error {
	if n.Signal == nil {
		return fmt.Errorf("backend(c): until without signal")
	}
	p := ind(depth)
	name := sigStateName(n)
	timeout := "-1"
	if n.TimeoutMS != nil {
		t, err := g.emitExpr(n.TimeoutMS)
		if err != nil {
			return err
		}
		timeout = t + ".i"
	}
	fmt.Fprintf(b, "%shm_pal_cond_wait_flag(&%s.cv, &%s.flag, %s);\n", p, name, name, timeout)
	return nil
}

// slotEntry 是编译期解析到的槽：谁的函数、捕获了哪些变量下标、频道是什么。
type slotEntry struct {
	onID    int
	channel string // "" = 全局槽（chan 是 Go 关键字，不能当字段名）
	capIDs  []int
}

// slotsFor 在**编译期**把 emit 与 on 配好对。
//
// 为什么不做运行期二分查找：emit 的信号名与频道都是编译期常量（频道在
// parser 层就要求纯字面量），那么"哪些槽可能被命中"在编译期就是确定的。
// 直接展开成串行的条件调用，连查表都省了 —— 这是零开销最彻底的形式。
// 跨编译单元（另一个 .hbc 里定义的槽）以后需要一张真正的静态表，那时再加。
func (g *cGen) slotsFor(sig, channel string, wantChan bool) []slotEntry {
	var out []slotEntry
	for ni := range g.wf.Nodes {
		n := &g.wf.Nodes[ni]
		if n.K != "on" || n.Signal == nil || *n.Signal != sig {
			continue
		}
		// 路由匹配：全局 emit 只命中全局槽；频道 emit 只命中同频道槽。
		haveChan := n.Chan != nil
		if wantChan != haveChan {
			continue
		}
		if wantChan && channel != "" && n.Chan != nil {
			if hashName(channel) != *n.Chan {
				continue
			}
		}
		e := slotEntry{onID: n.ID}
		for _, name := range n.Captures {
			for vi := range g.wf.Vars {
				if g.wf.Vars[vi].Name == name {
					e.capIDs = append(e.capIDs, g.wf.Vars[vi].ID)
					break
				}
			}
		}
		out = append(out, e)
	}
	return out
}

// hashName 与 C++ codegen 的 fnv1a64 必须逐位一致：IR 里的频道号就是它算的。
func hashName(s string) uint64 {
	h := uint64(1469598103934665603)
	for i := 0; i < len(s); i++ {
		h ^= uint64(s[i])
		h *= 1099511628211
	}
	return h
}

// emitSignal 生成"构造上下文 → 间接调用 → 短路"的代码。
//
// 短路的语义：槽返回非 0 表示已处理，后面的槽（外层作用域的）不再执行。
func (g *cGen) emitSignal(b *strings.Builder, n *ir.Node, depth int) error {
	if n.Signal == nil {
		return fmt.Errorf("backend(c): emit without signal")
	}
	p := ind(depth)
	wantChan := n.Route != nil && *n.Route == 1
	// 频道匹配用 IR 里的哈希直接比（slotEntry 比较的是 on.Chan），
	// 所以这里不需要原文；空串表示"按 wantChan 分桶"。
	entries := g.slotsFor(*n.Signal, "", wantChan)
	if len(entries) == 0 {
		// 没有槽：emit 是空操作，但保留求值语义（负载里可能有副作用）。
		fmt.Fprintf(b, "%s(void)0; /* emit %s: no handler in this unit */\n", p, *n.Signal)
		return nil
	}
	skip := fmt.Sprintf("hm_emit_skip_%d", n.ID)
	for _, e := range entries {
		if len(e.capIDs) > 0 {
			fmt.Fprintf(b, "%s{ struct hm_ctx_%d c%d;\n", p, e.onID, e.onID)
			for _, id := range e.capIDs {
				fmt.Fprintf(b, "%s  c%d.v%d = var_%d;\n", p, e.onID, id, id)
			}
			// 回调写完**必须回写**：槽捕获的是变量而不是值的快照，槽里
			// `hits = hits + 1` 之后调用方的 hits 也要变。不回写的话程序
			// 能编能跑，只是结果永远不变 —— 最难查的一类静默错误。
			fmt.Fprintf(b, "%s  int r%d = hm_slot_%d(&c%d);\n", p, e.onID, e.onID, e.onID)
			for _, id := range e.capIDs {
				fmt.Fprintf(b, "%s  var_%d = c%d.v%d;\n", p, id, e.onID, id)
			}
			fmt.Fprintf(b, "%s  if (r%d) goto %s; }\n", p, e.onID, skip)
		} else {
			fmt.Fprintf(b, "%sif (hm_slot_%d(0)) goto %s;\n", p, e.onID, skip)
		}
	}
	// 全局兜底：静态配对没命中时（走到这里说明没有槽认领）才查全局表。
	// 认领的槽会 goto skip，跳过这一行 —— 所以同单元的槽不会被调用两次。
	fmt.Fprintf(b, "%shm_slot_dispatch(0x%016xULL, 0x%016xULL);\n", p,
		hashName(*n.Signal), chanKey(n))
	fmt.Fprintf(b, "%s: ;\n", skip)
	// 唤醒等待该 (signal, channel) 的 until。emit 先分发本地槽再唤醒：
	// 槽里如果又 emit 了别的信号，唤醒顺序与源码顺序一致。
	fmt.Fprintf(b, "%shm_pal_cond_set_flag(&%s.cv, &%s.flag);\n", p, sigStateName(n), sigStateName(n))
	return nil
}

// genSlots 生成所有 `on` 的上下文结构体与槽函数。
//
// 为什么字段一律是 Val：捕获变量的静态类型在**编译期**已知，但槽体里对它的
// 每次读写都是 Val 语义（hm_int / hm_truthy / hm_str），用具体 C 类型反而要
// 在每个使用点做一次转换。Val 是产物里的通用值形态，宽度固定，无装箱。
func (g *cGen) genSlots(doc *ir.Doc) (string, error) {
	var out strings.Builder
	for wi := range doc.Workflows {
		wf := &doc.Workflows[wi]
		for ni := range wf.Nodes {
			n := &wf.Nodes[ni]
			if n.K != "on" || n.Body == nil {
				continue
			}
			// 名字 → 变量下标：IR 里 on 只带捕获的**名字**。
			idx := make([]int, 0, len(n.Captures))
			for _, name := range n.Captures {
				for vi := range wf.Vars {
					if wf.Vars[vi].Name == name {
						idx = append(idx, wf.Vars[vi].ID)
						break
					}
				}
			}
			caps := make(map[int]bool, len(idx))
			for _, id := range idx {
				caps[id] = true
			}

			// 跨单元可见的槽（export signal）需要一份静态注册存储。
			exported := n.Exported != nil && *n.Exported
			if exported {
				fmt.Fprintf(&out, "static hm_global_slot hm_greg_%d;\n", n.ID)
			}
			// 上下文结构体：字段名 v<下标>，与 IR 的变量编号一一对应。
			fmt.Fprintf(&out, "struct hm_ctx_%d {\n", n.ID)
			if len(idx) == 0 {
				out.WriteString("  int unused;\n")
			}
			for _, id := range idx {
				fmt.Fprintf(&out, "  Val v%d;\n", id)
			}
			out.WriteString("};\n")

			// 槽函数：在**新的 cGen 副本**上生成，只改 inSlot/capVars，
			// 其余（byID/varID/catchVars/errStack）与主函数一致 —— 任何一处
			// 不一致都会让槽体编译出与主函数不同的语义。
			sub := *g
			sub.inSlot = true
			sub.capVars = caps
			sub.errStack = nil
			sub.retStack = nil
			fmt.Fprintf(&out, "static int hm_slot_%d(void* raw) {\n", n.ID)
			if len(idx) > 0 {
				fmt.Fprintf(&out, "  struct hm_ctx_%d* c = (struct hm_ctx_%d*)raw; (void)c;\n", n.ID, n.ID)
			} else {
				out.WriteString("  (void)raw;\n")
			}
			var sb strings.Builder
			if err := sub.emitStmt(&sb, *n.Body, 1); err != nil {
				return "", err
			}
			out.WriteString(sb.String())
			// 默认"已处理"（短路）：槽体没有显式表达继续冒泡的语法，
			// 所以执行完即截断 —— 与用户选定的短路语义一致。
			out.WriteString("  return 1;\n")
			// 槽体里由共享代码路径产生的 `goto hm_fail` 必须有一个本函数的
			// 落点（main 的 hm_fail 在别的栈帧里）。只有真的引用了才定义，
			// 否则 -Wunused-label 会在用户产物里冒出来。
			if strings.Contains(sb.String(), "goto hm_fail") {
				out.WriteString("hm_fail:\n  return -1;\n")
			}
			out.WriteString("}\n")
		}
	}
	return out.String(), nil
}

// cIdentRE 是 extern 符号名的合法 C 标识符闭集。IR 的 fn 会被**原样拼进生成的
// C 源码**，不校验等于把源码注入面直接敞开 —— 编译期必须钉死。
var cIdentRE = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`)

// nativeCType 是 AOT 类型映射：IR 类型 → C 类型 / Val→C 转换 / C→Val 包装。
// 三者都与 cPrelude 的 Val 字段同源（long i / int b / char* s / double d）。
// v2.0.0：double 已进表（k=4，hm_as_double / hm_double）。cost / struct /
// array / httpresult 以及 Val 里根本没有的类型仍**不进这张表**：明确报错，
// 不假支持。§3.1 的 int64_t / uint8_t / hermes_str / opaque struct 完整映射
// 延后到 S2 的 cgo 桥。
type nativeCType struct {
	ctype string
	conv  string
	wrap  string
}

var nativeCTypes = map[string]nativeCType{
	"int":    {ctype: "long", conv: "hm_as_int", wrap: "hm_int"},
	"bool":   {ctype: "int", conv: "hm_truthy", wrap: "hm_bool"},
	"string": {ctype: "const char*", conv: "hm_as_str", wrap: "hm_str"},
	"double": {ctype: "double", conv: "hm_as_double", wrap: "hm_double"},
}

// nativeCTypeOf 把 IR 类型表达式映射到 C 类型；首版子集外一律明确报错。
func nativeCTypeOf(t *ir.TypeExpr, where string) (nativeCType, error) {
	if t == nil {
		return nativeCType{}, fmt.Errorf("backend(c): call_native %s has no type", where)
	}
	m, ok := nativeCTypes[t.K]
	if !ok {
		return nativeCType{}, fmt.Errorf("backend(c): call_native type %q is not in the AOT subset", t.K)
	}
	return m, nil
}

// nativePrototypes 在**编译期**为 unit 里每个被调 extern 符号写一条静态 C 原型。
// 没有 dlsym / 运行期符号表 / 运行期类型分发：原型与转换全部写死在生成的 C 里，
// 真正的符号由链接期（clang/ld）解析 —— 这就是 0 解释器的 AOT。
//
// 按 fn 去重；同名不同签名取第一个并在产物注释里注明（冲突诊断是另一张票
// #40，这一轮不做对账）。符号名必须过 cIdentRE，否则拒绝生成。
func nativePrototypes(doc *ir.Doc) (string, error) {
	if doc == nil {
		return "", nil
	}
	var b strings.Builder
	seen := map[string]bool{}
	for wi := range doc.Workflows {
		for i := range doc.Workflows[wi].Nodes {
			n := &doc.Workflows[wi].Nodes[i]
			if n.K != "call_native" {
				continue
			}
			if n.Fn == nil || *n.Fn == "" {
				return "", fmt.Errorf("backend(c): call_native node %d has no fn", n.ID)
			}
			fn := *n.Fn
			if !cIdentRE.MatchString(fn) {
				return "", fmt.Errorf("backend(c): call_native symbol %q is not a valid C identifier", fn)
			}
			if seen[fn] {
				continue
			}
			seen[fn] = true
			ret, err := nativeCTypeOf(n.Ret, "return type")
			if err != nil {
				return "", err
			}
			params := make([]string, 0, len(n.ArgTypes))
			for j := range n.ArgTypes {
				at, err := nativeCTypeOf(&n.ArgTypes[j], fmt.Sprintf("argument %d", j+1))
				if err != nil {
					return "", err
				}
				params = append(params, at.ctype)
			}
			if len(params) == 0 {
				// C99 里 (void) 才是"无参"；() 是不定参，会让原型失去约束力。
				params = append(params, "void")
			}
			fmt.Fprintf(&b, "extern %s %s(%s);\n", ret.ctype, fn, strings.Join(params, ", "))
		}
	}
	return b.String(), nil
}

type cGen struct {
	wf    *ir.Workflow
	doc   *ir.Doc
	byID  map[int]*ir.Node
	varID map[string]int
	// errStack 是当前嵌套的"错误去向"标签栈（try 的 catch 标签 / retry 的重试标签）。
	// 空栈表示未捕获 → hm_fail（打印错误、非零退出）。
	errStack []string
	// retStack 是"return 的去向"栈。默认 return 写 hm_result 并跳 hm_done；
	// 进入 fallback 降级块后，return 改为写该 fallback 的临时值并跳到它的收尾
	// —— 引擎里 fallback 的 `return` 只带出降级块的值，不是 workflow 的返回。
	retStack []retCtx
	// catchVars 把 catch 绑定的错误对象变量 id 映射到该 try 臂的**错误快照
	// 变量名**（`hm_errsnap_<tryID>`）。
	//
	// 运行期只有一个全局 HermesError hm_error。错误在 try 的 catch 臂被清错
	// 之前按值快照下来（见 case "try"），于是 `e.status` 直接读快照的 status
	// 字段（`hm_int((long)<snap>.status)`），而不是走 hm_field 取一个空字符串。
	// 这是本轮落地的 `e.status: int`（LANGUAGE §7.1.1）：错误对象在 C 运行期
	// 有了值形态，AOT 产物不再静默给出错值。
	//
	// 其它字段（url / message / type…）仍是**显式拒绝**：AOT 后端尚未带出
	// 这些字段，前端 E4034 亦未放行，不能静默 hm_field 成 null。
	catchVars map[int]string

	// ---- 闭包转换（2.0.1）--------------------------------------------------
	// inSlot 为 true 时，emittedExpr 处于某个槽函数内部。
	inSlot bool
	// capVars 是本槽**按引用捕获**的变量下标。命中时变量引用编成 `c->vN`
	// 而不是 `var_N` —— 后者在槽函数里根本不存在。
	capVars map[int]bool
}

type retCtx struct{ res, lbl string }

// exprOrFallback 求一个表达式槽：若是 fallback，先把它降成语句并返回临时值；
// 否则就是普通表达式。fallback 只在这个位置（decl/assign/return 的值）支持，
// 嵌在更深的表达式里会落到 emitExpr 的 default 报错。
func (g *cGen) exprOrFallback(b *strings.Builder, id *int, depth int) (string, error) {
	if fb, ok := g.fallbackOf(id); ok {
		return g.lowerFallback(b, fb, depth)
	}
	return g.emitExpr(id)
}

// fallbackOf 判断一个表达式槽是不是直接指向 fallback 节点。
func (g *cGen) fallbackOf(id *int) (*ir.Node, bool) {
	if id == nil {
		return nil, false
	}
	n, ok := g.byID[*id]
	if !ok || n.K != "fallback" {
		return nil, false
	}
	return n, true
}

// lowerFallback 把一个 fallback 表达式降成语句：先求 main，成功就取它；
// 失败（hm_error.code 置起）则清整个错误对象并跑降级块，取其 return 带出的值。
// 清错用 hm_clear_error()：code/status/msg 一起清，避免上一个错误的 status/msg
// 残留到降级块之后的逻辑里。返回临时变量名。
func (g *cGen) lowerFallback(b *strings.Builder, n *ir.Node, depth int) (string, error) {
	if n.Main == nil || n.Body == nil {
		return "", fmt.Errorf("backend(c): malformed fallback")
	}
	p := ind(depth)
	fb := fmt.Sprintf("hm_fb_%d", n.ID)
	mn := fmt.Sprintf("hm_mn_%d", n.ID)
	end := fmt.Sprintf("hm_fbend_%d", n.ID)
	mainExpr, err := g.emitExpr(n.Main)
	if err != nil {
		return "", err
	}
	fmt.Fprintf(b, "%sVal %s = hm_int(0);\n", p, fb)
	fmt.Fprintf(b, "%s{ Val %s = %s; if (!hm_error.code) { %s = %s; goto %s; } hm_clear_error(); }\n", p, mn, mainExpr, fb, mn, end)
	g.retStack = append(g.retStack, retCtx{res: fb, lbl: end})
	if err := g.emitStmt(b, *n.Body, depth); err != nil {
		g.retStack = g.retStack[:len(g.retStack)-1]
		return "", err
	}
	g.retStack = g.retStack[:len(g.retStack)-1]
	fmt.Fprintf(b, "%s%s: ;\n", p, end)
	return fb, nil
}

func (g *cGen) errLabel() string {
	if len(g.errStack) == 0 {
		return "hm_fail"
	}
	return g.errStack[len(g.errStack)-1]
}

func (g *cGen) node(id int) (*ir.Node, error) {
	n, ok := g.byID[id]
	if !ok {
		return nil, fmt.Errorf("backend(c): node %d does not exist", id)
	}
	return n, nil
}

func ind(depth int) string { return strings.Repeat("  ", depth) }

// emitStmt 把语句节点（seq/decl/assign/return/if）降成 C 语句。
func (g *cGen) emitStmt(b *strings.Builder, id, depth int) error {
	n, err := g.node(id)
	if err != nil {
		return err
	}
	p := ind(depth)
	// 与引擎的 stmt() 同步：每进入一个语句节点（含 seq 自身）就计一步。
	// 这是产物 `steps` 字段与 `hermes run` 逐字一致的前提。
	fmt.Fprintf(b, "%shm_steps++;\n", p)
	switch n.K {
	case "seq":
		for _, k := range n.Kids {
			if err := g.emitStmt(b, k, depth); err != nil {
				return err
			}
		}
	case "decl":
		if n.Var == nil {
			return fmt.Errorf("backend(c): decl without var")
		}
		expr, err := g.exprOrFallback(b, n.E, depth)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "%sVal var_%d = %s;\n", p, *n.Var, expr)
		fmt.Fprintf(b, "%sif (hm_error.code) goto %s;\n", p, g.errLabel())
	case "assign":
		if n.Var == nil {
			return fmt.Errorf("backend(c): assign without var")
		}
		expr, err := g.exprOrFallback(b, n.E, depth)
		if err != nil {
			return err
		}
		// 槽函数里写捕获变量 → 写上下文结构体字段（与读路径同一判据）。
		lhs := fmt.Sprintf("var_%d", *n.Var)
		if g.inSlot && g.capVars[*n.Var] {
			lhs = fmt.Sprintf("c->v%d", *n.Var)
		}
		fmt.Fprintf(b, "%s%s = %s;\n", p, lhs, expr)
		fmt.Fprintf(b, "%sif (hm_error.code) goto %s;\n", p, g.errLabel())
	case "return":
		expr, err := g.exprOrFallback(b, n.E, depth)
		if err != nil {
			return err
		}
		// 记下返回值并跳到收尾；若求值期间置了错误槽，先向外传播（不改结果、不 return）。
		// 若在 fallback 降级块里，return 只带出该块的值（写它的临时变量、跳它的收尾）。
		if len(g.retStack) > 0 {
			top := g.retStack[len(g.retStack)-1]
			fmt.Fprintf(b, "%s{ Val hm_r = %s; if (hm_error.code) goto %s; %s = hm_r; goto %s; }\n", p, expr, g.errLabel(), top.res, top.lbl)
		} else {
			fmt.Fprintf(b, "%s{ Val hm_r = %s; if (hm_error.code) goto %s; hm_result = hm_r; goto hm_done; }\n", p, expr, g.errLabel())
		}
	case "if":
		cond, err := g.emitExpr(n.C)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "%sif (hm_truthy(%s)) {\n", p, cond)
		if err := g.emitStmt(b, *n.Then, depth+1); err != nil {
			return err
		}
		for i := range n.Elifs {
			ec, err := g.emitExpr(&n.Elifs[i].C)
			if err != nil {
				return err
			}
			fmt.Fprintf(b, "%s} else if (hm_truthy(%s)) {\n", p, ec)
			if err := g.emitStmt(b, n.Elifs[i].Body, depth+1); err != nil {
				return err
			}
		}
		if n.Else != nil {
			fmt.Fprintf(b, "%s} else {\n", p)
			if err := g.emitStmt(b, *n.Else, depth+1); err != nil {
				return err
			}
		}
		fmt.Fprintf(b, "%s}\n", p)
	case "match":
		if n.Subj == nil {
			return fmt.Errorf("backend(c): match without subject")
		}
		sv, err := g.emitExpr(n.Subj)
		if err != nil {
			return err
		}
		mv := fmt.Sprintf("hm_m_%d", n.ID)
		fmt.Fprintf(b, "%sVal %s = %s;\n", p, mv, sv)
		first := true
		for i := range n.Arms {
			var cmp string
			if n.Arms[i].Num != nil {
				cmp = fmt.Sprintf("(%s.k==0 && %s.i==%dL)", mv, mv, *n.Arms[i].Num)
			} else {
				cmp = fmt.Sprintf("(%s.k==2 && strcmp(%s.s?%s.s:\"\", \"%s\")==0)", mv, mv, mv, cEscape(n.Arms[i].Lit))
			}
			if first {
				fmt.Fprintf(b, "%sif %s {\n", p, cmp)
				first = false
			} else {
				fmt.Fprintf(b, "%s} else if %s {\n", p, cmp)
			}
			if err := g.emitStmt(b, n.Arms[i].Body, depth+1); err != nil {
				return err
			}
		}
		if n.Default != nil {
			if first {
				fmt.Fprintf(b, "%s{\n", p)
			} else {
				fmt.Fprintf(b, "%s} else {\n", p)
			}
			if err := g.emitStmt(b, *n.Default, depth+1); err != nil {
				return err
			}
		}
		if !first || n.Default != nil {
			fmt.Fprintf(b, "%s}\n", p)
		}
	case "while":
		if n.C == nil || n.Body == nil {
			return fmt.Errorf("backend(c): malformed while")
		}
		cond, err := g.emitExpr(n.C)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "%swhile (hm_truthy(%s)) {\n", p, cond)
		if err := g.emitStmt(b, *n.Body, depth+1); err != nil {
			return err
		}
		fmt.Fprintf(b, "%s}\n", p)
	case "for":
		// C 的 for-post 正好是 `continue` 的目标（跳到步进而非条件），
		// 所以 for 用 C 的 for 头，不用 while 手工累加——后者会让 continue 跳过步进。
		if n.Init == nil || n.Cond == nil || n.Delta == nil || n.Var == nil || n.Body == nil {
			return fmt.Errorf("backend(c): malformed for")
		}
		initv, err := g.emitExpr(n.Init)
		if err != nil {
			return err
		}
		cond, err := g.emitExpr(n.Cond)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "%sfor (Val var_%d = %s; hm_truthy(%s); var_%d = hm_int(var_%d.i + (%dL))) {\n",
			p, *n.Var, initv, cond, *n.Var, *n.Var, *n.Delta)
		if err := g.emitStmt(b, *n.Body, depth+1); err != nil {
			return err
		}
		fmt.Fprintf(b, "%s}\n", p)
	case "emit":
		return g.emitSignal(b, n, depth)
	case "until":
		return g.emitUntil(b, n, depth)
	case "on":
		// 槽函数是**静态**定义（见 slots 段），这里只留一个取址引用，
		// 免得 -Wunused-function 在用户产物里冒出来。
		fmt.Fprintf(b, "%s(void)&hm_slot_%d;\n", p, n.ID)
	case "sleep":
		// 时长是**表达式**（可以不是字面量），所以运行期取值；单位在编译期
		// 已经折算成毫秒（parser 干的那件事）。
		if n.MS == nil {
			return fmt.Errorf("backend(c): malformed sleep (missing ms)")
		}
		msExpr, err := g.emitExpr(n.MS)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "%shm_sleep_ms(%s.i);\n", p, msExpr)
	case "break":
		fmt.Fprintf(b, "%sbreak;\n", p)
	case "continue":
		fmt.Fprintf(b, "%scontinue;\n", p)
	case "try":
		if n.Body == nil {
			return fmt.Errorf("backend(c): malformed try")
		}
		catchLbl := fmt.Sprintf("hm_catch_%d", n.ID)
		endLbl := fmt.Sprintf("hm_tryend_%d", n.ID)
		// body 里任何语句置起错误槽 → 跳到本 try 的 catch 标签。
		g.errStack = append(g.errStack, catchLbl)
		if err := g.emitStmt(b, *n.Body, depth+1); err != nil {
			return err
		}
		g.errStack = g.errStack[:len(g.errStack)-1]
		fmt.Fprintf(b, "%sgoto %s;\n", p, endLbl)
		fmt.Fprintf(b, "%s:\n", catchLbl)
		snapName := fmt.Sprintf("hm_errsnap_%d", n.ID)
		first := true
		for i := range n.Catches {
			c := &n.Catches[i]
			cond := errKindCond(c.T)
			if first {
				fmt.Fprintf(b, "%sif (%s) {\n", p, cond)
				first = false
			} else {
				fmt.Fprintf(b, "%s} else if (%s) {\n", p, cond)
			}
			cp := ind(depth + 1)
			// 声明集中在块首，且快照必须在清错之前：catch 体里的 `e.status`
			// 读这份快照的 status 字段（见 case "field"），而不是被清掉的
			// 全局 hm_error。每个 catch 臂各在自己的 {} 块内声明，互不冲突。
			fmt.Fprintf(b, "%sHermesError %s = hm_error_snapshot();\n", cp, snapName)
			// 绑定变量仍以空字符串占位，保证裸 `e` 引用有定义；`e.<field>`
			// 的字段访问由 case "field" 特判（status 读快照，其它字段拒绝）。
			fmt.Fprintf(b, "%sVal var_%d = hm_str(\"\");\n", cp, c.V)
			fmt.Fprintf(b, "%s(void)var_%d;\n", cp, c.V)
			fmt.Fprintf(b, "%shm_clear_error();\n", cp)
			if c.V >= 0 {
				g.catchVars[c.V] = snapName
			}
			if err := g.emitStmt(b, c.Body, depth+1); err != nil {
				return err
			}
		}
		if first {
			// 没有 catch 子句：错误继续向外传播。
			fmt.Fprintf(b, "%sgoto %s;\n", p, g.errLabel())
		} else {
			fmt.Fprintf(b, "%s} else {\n", p)
			fmt.Fprintf(b, "%sgoto %s;\n", ind(depth+1), g.errLabel())
			fmt.Fprintf(b, "%s}\n", p)
		}
		fmt.Fprintf(b, "%s:\n", endLbl)
	case "retry":
		if n.Body == nil || n.N == nil {
			return fmt.Errorf("backend(c): malformed retry")
		}
		contLbl := fmt.Sprintf("hm_retry_%d", n.ID)
		iv := fmt.Sprintf("hm_attempt_%d", n.ID)
		fmt.Fprintf(b, "%s{ long %s = 0; for (%s = 0; %s <= %d; %s++) {\n", p, iv, iv, iv, *n.N, iv)
		fmt.Fprintf(b, "%shm_clear_error();\n", ind(depth+1))
		g.errStack = append(g.errStack, contLbl)
		if err := g.emitStmt(b, *n.Body, depth+1); err != nil {
			return err
		}
		g.errStack = g.errStack[:len(g.errStack)-1]
		fmt.Fprintf(b, "%s%s: ;\n", ind(depth+1), contLbl)
		fmt.Fprintf(b, "%sif (!hm_error.code) break;\n", ind(depth+1))
		fmt.Fprintf(b, "%s}\n", p)
		fmt.Fprintf(b, "%sif (hm_error.code) goto %s;\n", p, g.errLabel())
		fmt.Fprintf(b, "%s}\n", p)
	default:
		return fmt.Errorf("backend(c): statement node %q is not in the S0 subset", n.K)
	}
	return nil
}

// emitExpr 把表达式节点降成一段 C 表达式（求值为 Val）。
func (g *cGen) emitExpr(id *int) (string, error) {
	if id == nil {
		return "", fmt.Errorf("backend(c): expression slot is empty")
	}
	n, err := g.node(*id)
	if err != nil {
		return "", err
	}
	switch n.K {
	case "lit":
		return g.emitLit(n)
	case "var":
		if n.Var == nil {
			return "", fmt.Errorf("backend(c): var node without var")
		}
		// 槽函数里：捕获变量在上下文结构体上，不是主函数的局部变量。
		if g.inSlot && g.capVars[*n.Var] {
			return fmt.Sprintf("c->v%d", *n.Var), nil
		}
		return fmt.Sprintf("var_%d", *n.Var), nil
	case "binop":
		if n.Op == nil || n.L == nil || n.R == nil {
			return "", fmt.Errorf("backend(c): malformed binop")
		}
		l, err := g.emitExpr(n.L)
		if err != nil {
			return "", err
		}
		r, err := g.emitExpr(n.R)
		if err != nil {
			return "", err
		}
		fn, ok := binopFn[*n.Op]
		if !ok {
			return "", fmt.Errorf("backend(c): binop %q is not in the S0 subset", *n.Op)
		}
		return fmt.Sprintf("%s(%s, %s)", fn, l, r), nil
	case "unop":
		if n.Op == nil || n.E == nil {
			return "", fmt.Errorf("backend(c): malformed unop")
		}
		e, err := g.emitExpr(n.E)
		if err != nil {
			return "", err
		}
		fn, ok := unopFn[*n.Op]
		if !ok {
			return "", fmt.Errorf("backend(c): unop %q is not in the S0 subset", *n.Op)
		}
		return fmt.Sprintf("%s(%s)", fn, e), nil
	case "interp":
		acc := `hm_str("")`
		for _, part := range n.Parts {
			if len(part.Path) > 0 {
				// 单段 path（`{name}`）在 S0 里按变量名解析；多段（`{a.b}`）留给后续。
				if len(part.Path) != 1 {
					return "", fmt.Errorf("backend(c): nested interpolation path is not in the S0 subset")
				}
				vid, ok := g.varID[part.Path[0]]
				if !ok {
					return "", fmt.Errorf("backend(c): interpolation references unknown variable %q", part.Path[0])
				}
				acc = fmt.Sprintf("hm_cat(%s, var_%d)", acc, vid)
			} else {
				acc = fmt.Sprintf("hm_cat(%s, hm_str(\"%s\"))", acc, cEscape(part.Lit))
			}
		}
		return acc, nil
	case "call_model":
		var ma ir.ModelArgs
		if len(n.Args) > 0 {
			if err := json.Unmarshal(n.Args, &ma); err != nil {
				return "", fmt.Errorf("backend(c): call_model args: %w", err)
			}
		}
		if ma.Prompt == nil {
			return "", fmt.Errorf("backend(c): call_model without prompt")
		}
		promptE, err := g.emitExpr(ma.Prompt)
		if err != nil {
			return "", err
		}
		maxTok := -1
		if ma.MaxTokens != nil {
			maxTok = *ma.MaxTokens
		}
		schema := "null"
		if n.Schema != nil && g.doc != nil && *n.Schema >= 0 && *n.Schema < len(g.doc.Schemas) {
			schema = string(g.doc.Schemas[*n.Schema].JSON)
		}
		return fmt.Sprintf(`hm_net_model_call(%s, "%s", %d, "%s", "%s", "%s", "%s")`,
			promptE, cEscape(ma.Precision), maxTok, cEscape(ma.Temperature),
			cEscape(schema), cEscape(g.wf.Backend), cEscape(g.wf.Name)), nil
	case "call_tool":
		var ta ir.ToolArgs
		if len(n.Args) > 0 {
			if err := json.Unmarshal(n.Args, &ta); err != nil {
				return "", fmt.Errorf("backend(c): call_tool args: %w", err)
			}
		}
		if ta.URL == nil {
			return "", fmt.Errorf("backend(c): call_tool without url")
		}
		urlE, err := g.emitExpr(ta.URL)
		if err != nil {
			return "", err
		}
		headerE := `hm_jsonv("null")`
		if ta.Header != nil {
			if headerE, err = g.emitExpr(ta.Header); err != nil {
				return "", err
			}
		}
		bodyE := `hm_jsonv("null")`
		if ta.Body != nil {
			if bodyE, err = g.emitExpr(ta.Body); err != nil {
				return "", err
			}
		}
		var allow strings.Builder
		allow.WriteString("[")
		for i, s := range ta.AllowStatus {
			if i > 0 {
				allow.WriteString(",")
			}
			fmt.Fprintf(&allow, "%d", s)
		}
		allow.WriteString("]")
		timeout := 0
		if ta.TimeoutMS != nil {
			timeout = *ta.TimeoutMS
		}
		tool := ""
		if n.Tool != nil {
			tool = *n.Tool
		}
		// 运行期把参数拼成 JSON 调 hermes_net_tool；非 0 状态由边界 helper
		// 把 code/status/msg 发布到全局 hm_error，于是 try/catch/fallback/retry
		// 对网络失败生效，catch 里也能读到 e.status。
		return fmt.Sprintf(`hm_net_tool_call(%s, %s, %s, "%s", "%s", %d, "%s", "%s")`,
			urlE, headerE, bodyE, cEscape(ta.Method), allow.String(), timeout,
			cEscape(g.wf.Name), cEscape(tool)), nil
	case "call_native":
		// 编译期静态调用：extern 原型由 nativePrototypes 写死在 C 前导之后，
		// 符号由链接期解析。不生成任何运行期符号表 / 类型分发 / dlsym。
		if n.Fn == nil || *n.Fn == "" {
			return "", fmt.Errorf("backend(c): call_native without fn")
		}
		if !cIdentRE.MatchString(*n.Fn) {
			return "", fmt.Errorf("backend(c): call_native symbol %q is not a valid C identifier", *n.Fn)
		}
		ret, err := nativeCTypeOf(n.Ret, "return type")
		if err != nil {
			return "", err
		}
		var argIDs []int
		if err := json.Unmarshal(n.Args, &argIDs); err != nil {
			return "", fmt.Errorf("backend(c): call_native args: %w", err)
		}
		// args（节点 id）与 arg_types（静态类型表）必须一一对应：
		// 不一致就是坏 IR，静默按短的那一侧生成会编出错误的 C 原型调用。
		if len(argIDs) != len(n.ArgTypes) {
			return "", fmt.Errorf("backend(c): call_native %q has %d args but %d arg_types (inconsistent IR)",
				*n.Fn, len(argIDs), len(n.ArgTypes))
		}
		parts := make([]string, 0, len(argIDs))
		for i := range argIDs {
			at, err := nativeCTypeOf(&n.ArgTypes[i], fmt.Sprintf("argument %d", i+1))
			if err != nil {
				return "", err
			}
			e, err := g.emitExpr(&argIDs[i])
			if err != nil {
				return "", err
			}
			parts = append(parts, fmt.Sprintf("%s(%s)", at.conv, e))
		}
		// hm_str 包装的是 C 函数返回的 const char*，**不复制**：约定被调用方
		// 返回静态存储期、或生命周期覆盖本次调用的缓冲区（与 Val.s 的借用
		// 语义一致）。全程单个 C 表达式，无需临时变量。
		return fmt.Sprintf("%s(%s(%s))", ret.wrap, *n.Fn, strings.Join(parts, ", ")), nil
	case "field":
		if n.Of == nil || n.Name == nil {
			return "", fmt.Errorf("backend(c): malformed field access")
		}
		// catch 绑定的错误对象：错误在 try 的 catch 臂清错前已按值快照，
		// 这里从 catchVars 取到快照变量名。LANGUAGE §7.1.1 只把 `e.status`
		// 列为 ready：直接读快照的 status 字段，不再静默走 hm_field 空串。
		// 其它字段（url / message / type…）AOT 后端尚未带出，前端 E4034 亦
		// 未放行，必须显式拒绝 —— 静默 null 会让 `if (e.url == ...)` 编得过、
		// 跑出错值，比拒绝坏得多。
		if base := g.byID[*n.Of]; base != nil && base.K == "var" && base.Var != nil {
			if snap, ok := g.catchVars[*base.Var]; ok {
				if *n.Name == "status" {
					return fmt.Sprintf("hm_int((long)%s.status)", snap), nil
				}
				return "", fmt.Errorf("backend(c): field %q of a caught error is not carried by "+
					"the AOT backend yet (frontend E4034 also does not allow it); only `status` is "+
					"available on the error object in AOT output; use `hermes run` for interpreter output", *n.Name)
			}
		}
		of, err := g.emitExpr(n.Of)
		if err != nil {
			return "", err
		}
		return fmt.Sprintf("hm_field(%s, \"%s\")", of, cEscape(*n.Name)), nil
	case "cast":
		// 动态值模型下 cast 基本是恒等；但 char/short 要按 C 宽度截断（符号扩展），
		// 与引擎 cast() 的 int8/int16 截断保持一致。
		inner, err := g.emitExpr(n.E)
		if err != nil {
			return "", err
		}
		if n.To != nil {
			switch n.To.K {
			case "char":
				return fmt.Sprintf("hm_int((long)(signed char)((%s).i))", inner), nil
			case "short":
				return fmt.Sprintf("hm_int((long)(short)((%s).i))", inner), nil
			case "int":
				return fmt.Sprintf("hm_int(hm_as_int(%s))", inner), nil
			case "string":
				return fmt.Sprintf("hm_str(hm_as_str(%s))", inner), nil
			case "bool":
				return fmt.Sprintf("hm_bool(hm_truthy(%s))", inner), nil
			case "double":
				// `json.as_float` 的 API 名保留，但 cast 目标已是 double。
				return fmt.Sprintf("hm_double(hm_as_double(%s))", inner), nil
			}
		}
		return inner, nil
	default:
		return "", fmt.Errorf("backend(c): expression node %q is not in the S0 subset", n.K)
	}
}

func (g *cGen) emitLit(n *ir.Node) (string, error) {
	if n.LitT == nil {
		return "", fmt.Errorf("backend(c): lit without type tag")
	}
	switch *n.LitT {
	case "int":
		var i int64
		if err := json.Unmarshal(n.LitV, &i); err != nil {
			return "", fmt.Errorf("backend(c): bad int literal: %w", err)
		}
		return fmt.Sprintf("hm_int(%dL)", i), nil
	case "bool":
		var b bool
		if err := json.Unmarshal(n.LitV, &b); err != nil {
			return "", fmt.Errorf("backend(c): bad bool literal: %w", err)
		}
		if b {
			return "hm_bool(1)", nil
		}
		return "hm_bool(0)", nil
	case "string":
		var s string
		if err := json.Unmarshal(n.LitV, &s); err != nil {
			return "", fmt.Errorf("backend(c): bad string literal: %w", err)
		}
		return fmt.Sprintf("hm_str(\"%s\")", cEscape(s)), nil
	case "null":
		return `hm_str("")`, nil
	case "double":
		// IR 里的 double 常量是位模式对象 {"k":"double","bits":"<16 位小写 hex>"}。
		// bits 是字符串（不是 JSON 数字），16 位小写 hex = math.Float64bits 的
		// uint64 用 %016x 格式化。发 shortest round-trip 的 C double 字面量，
		// 别用 %f（丢精度）或 %v（不是 C 字面量）。
		var bp struct {
			K    string `json:"k"`
			Bits string `json:"bits"`
		}
		if err := json.Unmarshal(n.LitV, &bp); err != nil {
			return "", fmt.Errorf("backend(c): bad double bit pattern: %w", err)
		}
		if bp.K != "double" || len(bp.Bits) != 16 {
			return "", fmt.Errorf("backend(c): double literal needs {\"k\":\"double\",\"bits\":\"<16 hex>\"}, got %s", string(n.LitV))
		}
		for i := 0; i < len(bp.Bits); i++ {
			c := bp.Bits[i]
			if !((c >= '0' && c <= '9') || (c >= 'a' && c <= 'f')) {
				return "", fmt.Errorf("backend(c): double bits %q is not 16 lowercase hex digits", bp.Bits)
			}
		}
		u, err := strconv.ParseUint(bp.Bits, 16, 64)
		if err != nil {
			return "", fmt.Errorf("backend(c): double bits %q is not valid hex: %w", bp.Bits, err)
		}
		// 指数全 1 = NaN/±Inf：FormatFloat 会吐 "+Inf"/"NaN"，不是合法 C 字面量。
		// 用位模式直构，避免生成编不过的 C（也覆盖 C ABI 直调塞进来的坏 IR）。
		// 这里只按位模式判断，不引入具名的非有限值判定：那道判定守在序列化边界，
		// 别处再起一份会把语义改成"非有限值不可构造/传递"。
		if (u>>52)&0x7ff == 0x7ff {
			return fmt.Sprintf("hm_double_from_bits(0x%sULL)", bp.Bits), nil
		}
		x := math.Float64frombits(u)
		return fmt.Sprintf("hm_double(%s)", strconv.FormatFloat(x, 'g', -1, 64)), nil
	default:
		return "", fmt.Errorf("backend(c): literal type %q is not in the S0 subset", *n.LitT)
	}
}


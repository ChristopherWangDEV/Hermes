package header

import (
	"fmt"
	"strings"

	"hermes/internal/ir"
)

// GenCPP 生成 `.hpp`（T47 的第二半）。
//
// **红线在这里**：Linux 上 clang++ 默认链接 **libstdc++（GPL-3.0 + Runtime Exception）**，
// 而 macOS 用 libc++（Apache-2.0 WITH LLVM-exception）。按 D-024 的从严原则，
// 生成的 `.hpp` 必须能在**完全不碰 C++ 标准库**的情况下工作：
//
//	默认（HERMES_CPP_NO_STD 语义）= 纯 C 声明 + extern "C"，一个 C++ 头都不 include；
//	定义 HERMES_CPP_WRAPPERS 才出现命名空间与薄包装（仍不 include 标准库）。
//
// 这就是为什么默认值和 C 头几乎一样：**"能在 C++ 里用"不需要标准库**，
// 需要的是能编译、能链接、类型正确。便利层是显式 opt-in，不是默认。
func GenCPP(doc *ir.Doc) ([]byte, error) {
	unit := Sanitize(doc.Unit.Name)
	var b strings.Builder

	fmt.Fprintf(&b, "/* Generated by hermes header --cpp; **do not edit**. Source: %s */\n", sanitizePath(doc.Unit.EntryPath))
	b.WriteString("/* By default **no C++ standard library headers are included**: on Linux clang++ links libstdc++ (GPL) by default.\n")
	b.WriteString(" * The convenience layer appears only when HERMES_CPP_WRAPPERS is defined, and still pulls in no standard library. */\n\n")

	guard := strings.ToUpper("HERMES_" + unit + "_HPP")
	fmt.Fprintf(&b, "#ifndef %s\n#define %s\n\n", guard, guard)
	b.WriteString("#include \"hermes/hermes_core.h\"\n\n")
	b.WriteString("#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n")

	names := make([]string, 0, len(doc.Types))
	for i := range doc.Types {
		if doc.Types[i].Exported {
			names = append(names, doc.Types[i].Name)
		}
	}
	for _, n := range names {
		fmt.Fprintf(&b, "typedef struct hermes_%s_%s hermes_%s_%s;\n", unit, Sanitize(n), unit, Sanitize(n))
	}
	if len(names) > 0 {
		b.WriteString("\n")
	}
	for i := range doc.Workflows {
		w := &doc.Workflows[i]
		if !w.Exported {
			continue
		}
		fmt.Fprintf(&b, "hermes_status hermes_%s_%s(const hermes_buf* input_json, hermes_buf* out_json);\n",
			unit, Sanitize(w.Name))
	}

	b.WriteString("\n#ifdef __cplusplus\n}\n#endif\n\n")

	// 便利层：**默认不存在**。它只用语言特性（命名空间、inline、引用），
	// 不 include <string> / <string_view> / <system_error> —— 那些一进来就
	// 把 libstdc++ 的许可问题带进来。
	b.WriteString("/* Convenience layer: enabled only when HERMES_CPP_WRAPPERS is defined. **No standard library dependency**. */\n")
	b.WriteString("#if defined(__cplusplus) && defined(HERMES_CPP_WRAPPERS)\n")
	fmt.Fprintf(&b, "namespace hermes { namespace %s {\n\n", unit)
	b.WriteString("inline hermes_status run(const char* input, size_t input_len, hermes_buf* out) {\n")
	b.WriteString("  hermes_buf in;\n")
	b.WriteString("  in.ptr = const_cast<char*>(input);\n")
	b.WriteString("  in.len = input_len;\n")
	wfCount := 0
	for i := range doc.Workflows {
		if doc.Workflows[i].Exported {
			wfCount++
		}
	}
	if wfCount == 1 {
		for i := range doc.Workflows {
			if doc.Workflows[i].Exported {
				fmt.Fprintf(&b, "  return hermes_%s_%s(&in, out);\n", unit, Sanitize(doc.Workflows[i].Name))
			}
		}
	} else {
		// 多个 workflow 时不猜调用哪个——那不是便利层该做的决定。
		b.WriteString("  (void)in;\n  (void)out;\n  return HERMES_ERR_INVALID_ARG;\n")
	}
	b.WriteString("}\n\n")
	fmt.Fprintf(&b, "} }  /* namespace hermes::%s */\n", unit)
	b.WriteString("#endif /* HERMES_CPP_WRAPPERS */\n\n")
	fmt.Fprintf(&b, "#endif /* %s */\n", guard)
	return []byte(b.String()), nil
}

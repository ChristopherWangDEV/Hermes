package importhomo

import (
	"fmt"
	"sort"
	"strings"
)

// Result 是一次导入的产物。
type Result struct {
	// Source 是生成的 `.hermes` 源码。同一份 plan 两次导入必须逐字节相等。
	Source []byte
	// Warnings 是"看懂了但没导"的东西。**不是失败**：认不透就少导几项，
	// 让人在自己的 diff 里看到少了什么，比猜着导对得多。
	Warnings []string
}

// recognized 是导入器唯一理解的 argv 节（T43 ⑦）。
//
// 只有两个：
//   - `--http`  网关的监听地址 → 变成 backend 的字面地址
//   - `--model` 模型清单 → 只作注释（运行期以 /v1/models 为准）
//
// 其余一切 flag 都不碰。这条清单短到可以一眼看完，是刻意的：**任何需要解释
// "这个 flag 是什么意思"的导入，都是在 Hermes 里重建 Homonoia 的 CLI 语义**，
// 而 D-023 的三条理由里有两条正是这么死的。
var recognized = map[string]bool{
	"--http":  true,
	"--model": true,
}

// Emit 把计划转成 `.hermes` 源码。
//
// 输出里只有两类东西：**源码**（backend 声明 + 一个占位 workflow）与**注释**
// （步骤清单、模型清单、未识别的参数）。没有第三条：导入器不是编译器，
// 它不产出"半成品 IR"，也不产出旁路 JSON。
func Emit(steps []Step) Result {
	var warnings []string
	warned := map[string]bool{}

	var httpAddr string
	var httpRaw string
	var models []string
	var defaultModel string

	for _, s := range steps {
		for i := 0; i < len(s.Argv); i++ {
			arg := s.Argv[i]
			if !strings.HasPrefix(arg, "--") {
				continue
			}
			// 值取下一个参数；以 `--` 开头说明没有值（或下一个 flag），不猜。
			var val string
			hasVal := i+1 < len(s.Argv) && !strings.HasPrefix(s.Argv[i+1], "--")
			if hasVal {
				val = s.Argv[i+1]
			}
			if !recognized[arg] {
				key := arg + "|" + s.Kind
				if !warned[key] {
					warned[key] = true
					warnings = append(warnings, fmt.Sprintf(
						"dropping unrecognized argument %s (from %s): the importer only understands --http and --model, "+
							"the meaning of the rest belongs to Homonoia and is not reconstructed here", arg, s.Kind))
				}
				continue
			}
			switch arg {
			case "--http":
				if hasVal && httpAddr == "" {
					httpRaw = val
					// `--http` 给的是 host:port，而 backend 的地址是完整 URL。
					// 补 scheme 只在缺的时候做：已经带 http:// / https:// 的照抄，
					// 免得把 `https://x` 变成 `http://https://x`。
					if !strings.Contains(val, "://") {
						val = "http://" + val
					}
					httpAddr = val
				}
			case "--model":
				if hasVal {
					models = append(models, val)
					if id, _, ok := strings.Cut(val, "="); ok && defaultModel == "" {
						defaultModel = id
					}
				}
			}
			if hasVal {
				i++ // 跳过值，避免把 `--model` 的路径当成另一个 flag
			}
		}
	}

	sort.Strings(warnings) // 顺序稳定：两次导入的 warning 也要逐字节可比

	var b strings.Builder

	b.WriteString("// Generated by `hermes import --from-plan`. Input is a Homonoia deployment plan.\n")
	b.WriteString("//\n")
	b.WriteString("// This file holds only deployment facts, no business semantics: a deploy script says what to start\n")
	b.WriteString("// (deployment and compute), a workflow says what to do (orchestration). The latter must be written by a human\n")
	b.WriteString("// -- the importer does not invent it (D-023 path A), so below is only a placeholder workflow.\n")
	b.WriteString("//\n")
	b.WriteString("// Steps in the plan (in order, for human reference only):\n")
	for i, s := range steps {
		note := ""
		if s.Note != nil {
			note = oneLine(*s.Note)
		}
		if note == "" {
			fmt.Fprintf(&b, "//   %d. %s\n", i+1, s.Kind)
		} else {
			fmt.Fprintf(&b, "//   %d. %s — %s\n", i+1, s.Kind, note)
		}
	}

	if len(models) > 0 {
		b.WriteString("//\n")
		b.WriteString("// Models seen at import time. At runtime /v1/models is authoritative; this is only the intent then:\n")
		for _, m := range models {
			// `id=path` 拆开写，纯粹为了可读：`chat = /tmp/x.gguf` 比
			// `chat=/tmp/x.gguf` 在 diff 里好认。拆不动的原样抄。
			if id, path, ok := strings.Cut(m, "="); ok {
				fmt.Fprintf(&b, "//   %s = %s\n", oneLine(id), oneLine(path))
			} else {
				fmt.Fprintf(&b, "//   %s\n", oneLine(m))
			}
		}
		if defaultModel != "" {
			fmt.Fprintf(&b, "//   default model (at import): %s\n", oneLine(defaultModel))
		}
	}

	b.WriteString("\n")

	if httpAddr != "" {
		fmt.Fprintf(&b, "// The gateway address comes from `--http %s` in the plan. A hard-coded literal is the import semantics,\n", oneLine(httpRaw))
		b.WriteString("// not a recommendation: distributions should use env(...) so the runtime environment decides the address.\n")
		fmt.Fprintf(&b, "backend homonoia = \"%s\";\n\n", escapeStringLit(httpAddr))
	}

	b.WriteString("workflow imported")
	if httpAddr != "" {
		b.WriteString("(backend = homonoia)")
	} else {
		b.WriteString("()")
	}
	b.WriteString(" entry -> string {\n")
	b.WriteString("    // Placeholder body: lets the frontend accept the file (zero entries are rejected by E3021), no business meaning.\n")
	b.WriteString("    // When writing real orchestration, use model.generate / tool.call; remember to #link the matching std module.\n")
	b.WriteString("    return \"TODO: describe what this workflow should do\";\n")
	b.WriteString("}\n")

	return Result{Source: []byte(b.String()), Warnings: warnings}
}

// oneLine 把多行文本压成一行：注释里出现换行会把后面的内容踢出注释，
// 变成一行源码——那是能把导入产物变成非法文件的最简单方式。
func oneLine(s string) string {
	s = strings.ReplaceAll(s, "\r\n", " ")
	s = strings.ReplaceAll(s, "\n", " ")
	s = strings.ReplaceAll(s, "\r", " ")
	return strings.TrimSpace(s)
}

// escapeStringLit 让地址安全地落进双引号字符串字面量。
func escapeStringLit(s string) string {
	s = strings.ReplaceAll(s, `\`, `\\`)
	s = strings.ReplaceAll(s, `"`, `\"`)
	return s
}
